/**
 * CSS properties the on-slide inspector may override, in kebab-case.
 *
 * Deliberately excludes anything that can pull in an external resource (`background-image`,
 * `content`, `filter`, `mask`, `cursor`): the sandbox has no network business, and a property
 * that accepts `url(...)` would be a way around that. Backgrounds have their own flow
 * (`ReactSlideConfig.background`) where the image is generated by us and served from our origin.
 */
export const EDITABLE_CSS_PROPERTIES = [
  'color',
  'background-color',
  'font-size',
  'font-weight',
  'font-family',
  'font-style',
  'line-height',
  'letter-spacing',
  'text-align',
  'text-transform',
  'text-shadow',
  'opacity',
  'padding',
  'margin',
  'border-radius',
  'border-width',
  'border-style',
  'border-color',
  'box-shadow',
  'width',
  'height',
  'min-width',
  'min-height',
  'max-width',
  'max-height',
  'display',
  'flex-direction',
  'justify-content',
  'align-items',
  'gap',
  'transform',
  'z-index',
] as const;

const EDITABLE_CSS_PROPERTY_SET: ReadonlySet<string> = new Set(EDITABLE_CSS_PROPERTIES);

/**
 * Values that could reach outside the sandbox or close the surrounding `<style>`/attribute.
 * `url(` covers remote images/fonts, `@import` remote stylesheets, `expression(` legacy IE
 * script, `javascript:` script URLs, and `<`/`}` markup or rule breakouts.
 */
const UNSAFE_CSS_VALUE = /url\s*\(|@import|expression\s*\(|javascript\s*:|<|\}|;/i;

export function isSafeCssValue(value: string): boolean {
  if (value.length === 0 || value.length > MAX_CSS_VALUE_LENGTH) return false;
  return !UNSAFE_CSS_VALUE.test(value);
}

export function isEditableCssProperty(property: string): boolean {
  return EDITABLE_CSS_PROPERTY_SET.has(property);
}

/**
 * Keep only overrides the sandbox is allowed to apply: known properties, safe values, and text
 * within the length cap. Invalid entries are dropped rather than rejected so one stale property
 * (e.g. saved by an older client) can't make a whole page unloadable.
 */
export function normalizeStyleOverrides(styles: Record<string, unknown> | undefined): Record<string, string> {
  const out: Record<string, string> = {};
  if (!styles) return out;
  for (const [rawProp, rawValue] of Object.entries(styles)) {
    const property = String(rawProp).trim().toLowerCase();
    if (!isEditableCssProperty(property)) continue;
    if (typeof rawValue !== 'string') continue;
    const value = rawValue.trim();
    if (!isSafeCssValue(value)) continue;
    out[property] = value;
  }
  return out;
}

/**
 * Element path assigned by the sandbox runtime: the chain of element-child indices from the
 * slide root, e.g. `0/2/1`. Element-only (text nodes are skipped) so it is insensitive to
 * whitespace, and computed at render time so the LLM never has to emit ids.
 */
const ELEMENT_PATH_RE = /^\d+(\/\d+)*$/;

export function isValidElementPath(path: string): boolean {
  return ELEMENT_PATH_RE.test(path) && path.length <= 200;
}

export interface ReactSlideOverride {
  text?: string;
  styles?: Record<string, string>;
}

export interface ReactSlideBackground {
  mode: 'none' | 'color' | 'image';
  color?: string;
  prompt?: string;
  /** Relative to the pdf storage dir, e.g. `pages/<uid>.slide-bg.png`. */
  file?: string;
  fit?: 'cover' | 'contain';
  position?: string;
  overlayColor?: string;
  overlayOpacity?: number;
}

export interface ReactSlideConfig {
  version: 1;
  prompt?: string;
  overrides: Record<string, ReactSlideOverride>;
  background: ReactSlideBackground;
  updated_at: string;
}

const CssColorSchema = z.string().trim().max(MAX_CSS_VALUE_LENGTH).refine(isSafeCssValue, 'unsafe css value');

const BackgroundSchema = z.object({
  mode: z.enum(['none', 'color', 'image']).default('none'),
  color: CssColorSchema.optional(),
  prompt: z.string().max(MAX_REACT_SLIDE_PROMPT_LENGTH).optional(),
  file: z.string().max(300).optional(),
  fit: z.enum(['cover', 'contain']).optional(),
  position: CssColorSchema.optional(),
  overlayColor: CssColorSchema.optional(),
  overlayOpacity: z.number().min(0).max(1).optional(),
});

const OverrideSchema = z.object({
  text: z.string().max(MAX_OVERRIDE_TEXT_LENGTH).optional(),
  styles: z.record(z.string(), z.unknown()).optional(),
});

export const ReactSlideConfigSchema = z.object({
  version: z.literal(1).default(1),
  prompt: z.string().max(MAX_REACT_SLIDE_PROMPT_LENGTH).optional(),
  overrides: z.record(z.string(), OverrideSchema).default({}),
  background: BackgroundSchema.default({ mode: 'none' }),
  updated_at: z.string().optional(),
});

export function defaultReactSlideConfig(): ReactSlideConfig {
  return { version: 1, overrides: {}, background: { mode: 'none' }, updated_at: new Date().toISOString() };
}

/**
 * Validate + normalize an incoming/stored config. Unknown element paths, unknown CSS properties
 * and unsafe values are dropped; a config that cannot be parsed at all falls back to the default
 * so a corrupted file renders an un-tweaked slide instead of breaking the page.
 */
export function sanitizeReactSlideConfig(input: unknown): ReactSlideConfig {
  const parsed = ReactSlideConfigSchema.safeParse(input);
  if (!parsed.success) return defaultReactSlideConfig();
  const overrides: Record<string, ReactSlideOverride> = {};
  let count = 0;
  for (const [path, value] of Object.entries(parsed.data.overrides)) {
    if (!isValidElementPath(path)) continue;
    if (count >= MAX_OVERRIDE_ENTRIES) break;
    const styles = normalizeStyleOverrides(value.styles as Record<string, unknown> | undefined);
    const text = typeof value.text === 'string' ? value.text : undefined;
    if (text === undefined && Object.keys(styles).length === 0) continue;
    overrides[path] = {
      ...(text !== undefined ? { text } : {}),
      ...(Object.keys(styles).length > 0 ? { styles } : {}),
    };
    count += 1;
  }
  const bg = parsed.data.background;
  return {
    version: 1,
    ...(parsed.data.prompt ? { prompt: parsed.data.prompt } : {}),
    overrides,
    background: {
      mode: bg.mode,
      ...(bg.color ? { color: bg.color } : {}),
      ...(bg.prompt ? { prompt: bg.prompt } : {}),
      ...(bg.file ? { file: bg.file } : {}),
      ...(bg.fit ? { fit: bg.fit } : {}),
      ...(bg.position ? { position: bg.position } : {}),
      ...(bg.overlayColor ? { overlayColor: bg.overlayColor } : {}),
      ...(bg.overlayOpacity !== undefined ? { overlayOpacity: bg.overlayOpacity } : {}),
    },
    updated_at: parsed.data.updated_at ?? new Date().toISOString(),
  };
}

export function parseStoredReactSlideConfig(raw: string): ReactSlideConfig {
  try {
    return sanitizeReactSlideConfig(JSON.parse(raw));
  } catch {
    return defaultReactSlideConfig();
  }
}

export interface SlideTheme {
  version: 1;
  name: string;
  tokens: Record<SlideThemeTokenKey, string>;
  customCss?: string;
  updated_at: string;
}

export function defaultSlideTheme(): SlideTheme {
  return {
    version: 1,
    name: 'Default',
    tokens: { ...DEFAULT_SLIDE_THEME_TOKENS },
    updated_at: new Date().toISOString(),
  };
}

const SlideThemeSchema = z.object({
  version: z.literal(1).default(1),
  name: z.string().trim().min(1).max(80).default('Default'),
  tokens: z.record(z.string(), z.unknown()).default({}),
  customCss: z.string().max(MAX_THEME_CUSTOM_CSS_LENGTH).optional(),
  updated_at: z.string().optional(),
});

/**
 * Custom CSS is injected into the sandbox verbatim, so it gets a coarser check than token values
 * (which are single declarations): only the constructs that reach outside the sandbox or escape
 * the `<style>` element are rejected. Braces and semicolons are legitimate here.
 */
const UNSAFE_CUSTOM_CSS = /url\s*\(|@import|expression\s*\(|javascript\s*:|<\s*\/?\s*script/i;

export function sanitizeSlideTheme(input: unknown): SlideTheme {
  const parsed = SlideThemeSchema.safeParse(input);
  if (!parsed.success) return defaultSlideTheme();
  const tokens: Record<SlideThemeTokenKey, string> = { ...DEFAULT_SLIDE_THEME_TOKENS };
  for (const key of SLIDE_THEME_TOKEN_KEYS) {
    const value = parsed.data.tokens[key];
    if (typeof value !== 'string') continue;
    const trimmed = value.trim();
    if (!isSafeCssValue(trimmed)) continue;
    tokens[key] = trimmed;
  }
  const customCss = typeof parsed.data.customCss === 'string' ? parsed.data.customCss : undefined;
  const safeCustomCss = customCss && !UNSAFE_CUSTOM_CSS.test(customCss) ? customCss : undefined;
  return {
    version: 1,
    name: parsed.data.name,
    tokens,
    ...(safeCustomCss ? { customCss: safeCustomCss } : {}),
    updated_at: parsed.data.updated_at ?? new Date().toISOString(),
  };
}

export function parseStoredSlideTheme(raw: string): SlideTheme {
  try {
    return sanitizeSlideTheme(JSON.parse(raw));
  } catch {
    return defaultSlideTheme();
  }
}

/**
 * Static safety check on slide code, sharing the custom-script animation's deny list (fetch,
 * XMLHttpRequest, WebSocket, import(), require(), eval, Function(), cookies, storage,
 * window.parent/top, frameElement) and adding the ES-module forms a JSX file can carry.
 *
 * The sandbox already blocks all of this at the browser level; this exists so obviously unsafe
 * code is rejected before it is ever stored, and so the user gets a specific reason instead of a
 * blank slide.
 */
export function findUnsafeReactSlideCode(code: string): string | null {
  if (/^\s*import\s+[^(]/m.test(code)) return 'import';
  if (/^\s*export\s+/m.test(code)) return 'export';
  return findUnsafeScriptPattern(code);
}

/** The contract the sandbox expects: a component exported through `window.SlideComponent`. */
export function findReactSlideContractIssue(code: string): string | null {
  if (!/window\s*\.\s*SlideComponent\s*=|window\s*\[\s*['"]SlideComponent['"]\s*\]\s*=/.test(code)) {
    return 'Generated code must assign the component to window.SlideComponent';
  }
  return null;
}

/**
 * Pull the code out of an LLM reply. Prefers a fenced block (```jsx / ```js / ```), because
 * models habitually wrap code even when told not to, and falls back to the raw text so a
 * well-behaved reply still works.
 */
export function extractJsxFromLlmOutput(output: string): string {
  const fenced = /```(?:jsx?|tsx?|javascript|react)?\s*\n([\s\S]*?)```/i.exec(output);
  const code = fenced ? (fenced[1] ?? '') : output;
  return code.trim();
}

export interface CompiledReactSlide {
  code: string;
  warnings: string[];
}

/**
 * Compile JSX to browser-ready JS with esbuild (`React.createElement` factory — the sandbox has
 * React as a global, not as a module).
 *
 * esbuild is imported dynamically so a runtime that shipped without it fails here with a clear
 * message at save time, rather than storing code that would only break once a viewer opens the
 * page. Compile errors are surfaced verbatim: they are the user's own syntax errors and the only
 * useful thing we can say about them.
 */
export async function compileReactSlide(source: string): Promise<CompiledReactSlide> {
  let transform: typeof import('esbuild').transform;
  try {
    ({ transform } = await import('esbuild'));
  } catch {
    throw new Error('JSX compiler (esbuild) is unavailable in this runtime');
  }
  const result = await transform(source, {
    loader: 'jsx',
    jsx: 'transform',
    jsxFactory: 'React.createElement',
    jsxFragment: 'React.Fragment',
    target: 'es2018',
    format: 'iife',
  });
  return { code: result.code, warnings: result.warnings.map((w) => w.text) };
}

export interface ReactSlideValidation {
  ok: boolean;
  /** Human-readable reason, already safe to show the user. */
  message?: string;
  compiled?: string;
}

/** Full save-time pipeline: length → deny list → contract → compile. */
export async function validateAndCompileReactSlide(source: string): Promise<ReactSlideValidation> {
  const code = source.trim();
  if (code.length === 0) return { ok: false, message: 'Slide code is empty' };
  if (code.length > MAX_REACT_SLIDE_CODE_LENGTH) {
    return { ok: false, message: `Slide code exceeds ${MAX_REACT_SLIDE_CODE_LENGTH} characters` };
  }
  const unsafe = findUnsafeReactSlideCode(code);
  if (unsafe) return { ok: false, message: `Slide code uses a disallowed API: ${unsafe}` };
  const contract = findReactSlideContractIssue(code);
  if (contract) return { ok: false, message: contract };
  try {
    const compiled = await compileReactSlide(code);
    return { ok: true, compiled: compiled.code };
  } catch (err) {
    return { ok: false, message: err instanceof Error ? err.message : String(err) };
  }
}


export interface ReactSlideGenerationInput {
  prompt: string;
  pageText?: string;
  pageScript?: string;
  currentCode?: string;
  theme: SlideTheme;
}

/**
 * The rules the generated component must follow. Written as hard constraints rather than advice
 * because each one maps to a way the page would otherwise break: no imports (nothing resolves in
 * the sandbox), no post-mount mutation (per-element overrides are applied once after render, so a
 * component that rewrites itself would erase them), tokens instead of literal colors (that is what
 * makes a deck-wide theme mean anything), and a 1920×1080 canvas (the frame scales, it does not
 * reflow).
 */
export function buildReactSlideSystemPrompt(theme: SlideTheme): string {
  const tokenList = SLIDE_THEME_TOKEN_KEYS.map((key) => `${key}: ${theme.tokens[key]}`).join('\n');
  return [
    '你是一位簡報設計工程師，負責用 React 撰寫一頁投影片。',
    '',
    '硬性規則：',
    '1. 只輸出一段 JSX 程式碼，用 ```jsx 圍籬包住，圍籬外不要有任何說明文字。',
    '2. 定義 `function Slide() { ... }`，最後一行必須是 `window.SlideComponent = Slide;`。',
    '3. 只能使用全域的 `React` 與 JSX。不可以 import / require / export，不可以 fetch、計時器、localStorage 或任何外部資源（含外部圖片網址與字型）。',
    '4. 元件必須是靜態的：掛載後不可再改寫自己的內容（畫面上的文字與樣式之後會由使用者的覆寫設定套用）。',
    '5. 版面固定為 1920×1080 的畫布，根節點請用 `width: \'100%\', height: \'100%\'`、`boxSizing: \'border-box\'`，不需要 responsive 寫法。',
    '6. 樣式只能用 inline `style={{...}}`（必要時可加一個 `<style>` 區塊），不可以使用 Tailwind 或任何 class library。',
    '7. 顏色、字體、字級、圓角、間距一律使用主題變數（例如 `var(--slide-accent)`），不要寫死色碼。',
    '8. 不要在元件內畫滿版底色，背景由外層負責。',
    '9. 投影片是「要點」不是逐字稿：文字精簡，一頁最多 6 個重點，字級要在 3 公尺外看得清楚。',
    '',
    '可用的主題變數：',
    tokenList,
  ].join('\n');
}

export function buildReactSlideMessages(input: ReactSlideGenerationInput): ChatCompletionMessageParam[] {
  const parts: string[] = [`使用者的描述：\n${input.prompt.trim()}`];
  if (input.pageScript?.trim()) {
    parts.push(`這一頁的逐字稿（投影片內容要與它呼應，但不要照抄）：\n${input.pageScript.trim().slice(0, 3000)}`);
  }
  if (input.pageText?.trim()) {
    parts.push(`這一頁原始頁面的文字（可作為事實依據）：\n${input.pageText.trim().slice(0, 3000)}`);
  }
  if (input.currentCode?.trim()) {
    parts.push(`目前這一頁的程式碼（請在此基礎上修改，保留使用者沒有要求變動的部分）：\n${input.currentCode.trim().slice(0, 8000)}`);
  }
  return [
    { role: 'system', content: buildReactSlideSystemPrompt(input.theme) },
    { role: 'user', content: parts.join('\n\n') },
  ];
}

/**
 * Ask the LLM for the page's React code and return it compiled. One retry is spent when the first
 * attempt fails validation, with the reason fed back to the model — the common failures (forgot
 * the `window.SlideComponent` line, a stray import, a JSX typo) are exactly the kind a model fixes
 * when told what broke.
 */
export async function generateReactSlideCode(
  input: ReactSlideGenerationInput,
): Promise<{ code: string; compiled: string }> {
  const messages = buildReactSlideMessages(input);
  let lastMessage = 'unknown error';
  for (let attempt = 0; attempt < 2; attempt += 1) {
    let output = '';
    await streamChatText({
      label: 'generate_react_slide',
      messages,
      maxTokens: 4000,
      temperature: 0.4,
      onDelta: (delta) => {
        output += delta;
      },
    });
    const code = extractJsxFromLlmOutput(output);
    const validation = await validateAndCompileReactSlide(code);
    if (validation.ok && validation.compiled) {
      return { code, compiled: validation.compiled };
    }
    lastMessage = validation.message ?? 'unknown error';
    messages.push({ role: 'assistant', content: output.slice(0, 8000) });
    messages.push({
      role: 'user',
      content: `上一次的程式碼無法使用，原因：${lastMessage}。請修正後重新輸出完整程式碼（同樣用 \`\`\`jsx 圍籬包住）。`,
    });
  }
  throw new Error(`React slide generation failed: ${lastMessage}`);
}

const GeneratedThemeSchema = z.object({
  name: z.string().min(1).max(80),
  tokens: z.record(z.string(), z.string()),
});

/**
 * Generate a deck-wide theme from one sentence. The model only ever returns token values, never
 * CSS rules — the token list is fixed, so a theme can restyle every page without being able to
 * inject anything the sandbox would have to evaluate.
 */
export async function generateSlideTheme(prompt: string, deckTitle?: string): Promise<SlideTheme> {
  const result = await callChatJSON({
    label: 'generate_slide_theme',
    schema: GeneratedThemeSchema,
    maxTokens: 1200,
    temperature: 0.6,
    messages: [
      {
        role: 'system',
        content: [
          '你是一位簡報視覺設計師，負責產生一組簡報主題設計變數。',
          '只回傳 JSON：{"name":"主題名稱","tokens":{"--slide-bg":"...", ...}}。',
          `tokens 只能包含這些鍵（全部都要給值）：${SLIDE_THEME_TOKEN_KEYS.join('、')}。`,
          '色彩用 #rrggbb；字體用 CSS font-family 字串（只能用系統字體或 "Noto Sans TC"，不可引用外部字型）；',
          '尺寸用 px（畫布是 1920×1080，標題級距通常 72~120px、內文 28~44px）；陰影用 box-shadow 語法。',
          '值裡不可以出現 url()、@import、分號或角括號。',
          '請確保前景色與背景色的對比足夠（投影機上仍看得清楚）。',
        ].join('\n'),
      },
      {
        role: 'user',
        content: deckTitle ? `簡報主題：${deckTitle}\n\n風格描述：${prompt}` : `風格描述：${prompt}`,
      },
    ],
  });
  return sanitizeSlideTheme({ version: 1, name: result.data.name, tokens: result.data.tokens });
}


/**
 * React slide pages (`render_type = 'react'`) — see docs/react-slide-design.md.
 *
 * A React slide is three artifacts that deliberately live apart from each other:
 *
 *  - the JSX source (`<uid>.slide.jsx`), written by the LLM or by hand;
 *  - its esbuild-compiled JS (`<uid>.slide.js`), the only thing the sandbox iframe executes;
 *  - a config (`<uid>.slide.json`) holding per-element text/CSS overrides and the background.
 *
 * Keeping the config out of the code is what makes "edit the text on the slide" survive a
 * regeneration of the code — and, conversely, what lets a user throw away their tweaks without
 * losing the layout. The deck-wide theme (design tokens) lives one level up, in
 * `slide-theme.json`, so restyling a whole presentation never touches a single page's code.
 *
 * Everything the browser will eventually evaluate passes through this module first: code goes
 * through `findUnsafeReactSlideCode()` (shared with the custom-script animation sandbox) and
 * every CSS value through `isSafeCssValue()`, so a page can never pull in an external resource
 * or reach the parent document.
 */

export const MAX_REACT_SLIDE_CODE_LENGTH = 60000;
export const MAX_REACT_SLIDE_PROMPT_LENGTH = 2000;
export const MAX_OVERRIDE_TEXT_LENGTH = 2000;
export const MAX_CSS_VALUE_LENGTH = 200;
export const MAX_OVERRIDE_ENTRIES = 200;
export const MAX_THEME_CUSTOM_CSS_LENGTH = 4000;


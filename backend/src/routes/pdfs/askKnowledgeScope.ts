// AI 導師（PageAskPanel）回答時「可以用哪些資訊」的規則。
//
// 預設只能依教材作答（禁止引入教材以外的知識），避免導師講出課程沒教、甚至是錯的內容。
// 但學生有時就是想知道教材沒寫的背景（例如某個名詞在業界的用法），這時前端的
// 「允許使用教材以外的資訊」勾選框會送 allowOutsideKnowledge: true，改用放寬版的規則。
// 放寬的是「資訊來源」，不是「可以亂講」：教材外的內容必須逐處標示，具體的數據與出處
// 仍然不准編造。
//
// 回傳的字串會直接接在 system prompt 的【引用規則】之後。未指定（undefined）視為不允許，
// 此時的內容與加入這個選項之前的 prompt 逐字相同。

export const TUTOR_OUTSIDE_KNOWLEDGE_MARKER = '（教材外補充）';

export function askKnowledgeScopeInstruction(allowOutsideKnowledge: boolean | undefined): string {
  if (allowOutsideKnowledge) {
    return `【資訊來源：允許使用教材以外的知識（務必遵守）】學生要求可以使用教材以外的資訊。請以上述教材內容為主：教材有涵蓋的部分先依教材作答；教材沒有涵蓋、或需要背景知識才能講清楚時，可以用你自己的一般知識補充。凡是來自教材以外的內容，都必須在該處標示「${TUTOR_OUTSIDE_KNOWLEDGE_MARKER}」（用你回答的語言標示即可），讓學生分得出哪些是課程內容、哪些不是。若教材的說法與你所知不同，請指出差異並說明教材的說法。仍然嚴禁編造具體的數據、引用、文獻或網址；不確定的地方要明說不確定。`;
  }
  return '【禁止杜撰（務必遵守）】你只能依據上述提供的頁面內容與原始來源作答，嚴禁杜撰、臆測或引入教材以外的知識；若所有提供的內容都找不到與問題相關的資訊，請直接明確說明在教材中找不到相關資訊（用你回答的語言表達即可，不必照抄這句話），並簡短建議學生換個問法或查看相關頁面，切勿編造答案。';
}
